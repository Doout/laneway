import { chromium, expect } from '@playwright/test'

const origin = new URL(process.env.LANEWAY_FLEET_LAB_ORIGIN)
if (origin.protocol !== 'https:' || origin.hostname !== 'laneway-fleet.test' || !origin.port) {
  throw new Error('The fleet console gate must run against its disposable loopback relay.')
}

const browser = await chromium.launch({ args: ['--host-resolver-rules=MAP laneway-fleet.test 127.0.0.1', '--no-proxy-server'] })
try {
  const context = await browser.newContext({ ignoreHTTPSErrors: true, serviceWorkers: 'block' })
  await context.route('**/*', (route) =>
    new URL(route.request().url()).origin === origin.origin ? route.continue() : route.abort())
  const page = await context.newPage()
  page.setDefaultTimeout(10_000)
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  const network = '/v1/admin/networks/' + process.env.LANEWAY_FLEET_LAB_NETWORK
  const source = 'console-source'
  const destination = 'console-destination'
  const destinationIP = process.env.LANEWAY_FLEET_LAB_DESTINATION_IP

  function visit(path) {
    return page.goto(new URL(path, origin).href, { waitUntil: 'domcontentloaded' })
  }

  async function request(method, path, trigger = () => {}) {
    const [response] = await Promise.all([
      page.waitForResponse((candidate) => {
        const url = new URL(candidate.url())
        return url.origin === origin.origin && candidate.request().method() === method &&
          (typeof path === 'string' ? url.pathname === path : path.test(url.pathname))
      }),
      trigger(),
    ])
    expect(response.ok(), `${method} ${new URL(response.url()).pathname}: HTTP ${response.status()}`).toBe(true)
    return response
  }

  await visit('/sign-in')
  await page.getByLabel('Username').fill(process.env.LANEWAY_FLEET_LAB_USERNAME)
  await page.getByLabel('Password').fill(process.env.LANEWAY_FLEET_LAB_PASSWORD)
  await request('POST', '/v1/admin/auth/login', () => page.getByRole('button', { name: 'Sign in' }).click())
  await expect(page).not.toHaveURL(/\/sign-in/)

  const updates = network + '/fleet-updates'
  await request('GET', updates, () => visit('/operations/updates'))
  await page.getByRole('button', { name: 'Schedule update' }).click()
  await page.getByLabel('Signed release tag').fill('v1.2.3')
  await page.getByLabel(`Update stage for ${destination}`).selectOption('canary')
  await request('POST', updates, () => page.getByRole('button', { name: 'Schedule canaries' }).click())
  const rollout = page.getByRole('article', { name: 'Release v1.2.3' })
  await rollout.getByText('Node results', { exact: true }).click()
  await expect(rollout.getByText(destination, { exact: true })).toBeVisible()
  await rollout.getByRole('button', { name: 'Cancel rollout' }).click()
  await request('POST', /\/fleet-updates\/[a-f0-9]+\/cancel$/, () =>
    page.getByRole('button', { name: 'Cancel unclaimed work' }).click())
  await page.getByLabel('Show rollouts').selectOption('history')
  await expect(rollout.getByText('Unclaimed work was cancelled.', { exact: true })).toBeVisible()
  console.log('fleet updates: scheduled and cancelled a disposable canary plan')

  await request('GET', network + '/alerts', () => visit('/operations/alerts'))
  const alert = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'node offline' }) })
  await request('POST', /\/alerts\/[a-f0-9]+\/acknowledge$/, () =>
    alert.getByRole('button', { name: 'Acknowledge' }).click())
  await expect(alert.getByText('acknowledged', { exact: true })).toBeVisible()
  console.log('alerts: acknowledged an offline event generated by Rust')

  await visit('/operations/diagnostics')
  await page.getByLabel('Source node').selectOption({ label: source })
  await page.getByRole('combobox', { name: /^Destination(?! type)/ }).selectOption({ label: destination })
  await request('POST', network + '/diagnostics', () => page.getByRole('button', { name: 'Check connection' }).click())
  await expect(page.getByRole('heading', { name: 'Policy decision: accept' })).toBeVisible()
  await expect(page.getByText('unknown', { exact: true })).toBeVisible()
  console.log('diagnostics: allowed by policy; end-to-end reachability remains unknown')

  await request('GET', network + '/private-dns', () => visit('/networks/dns'))
  await page.getByRole('searchbox', { name: 'Search DNS names' }).fill(destinationIP)
  await expect(page.getByText(destinationIP, { exact: true })).toBeVisible()
  console.log('private DNS: displayed the real catalog and filtered by node address')

  await request('GET', network + '/policy-history', () => visit('/access/preview'))
  await expect(page.getByRole('button', { name: 'Restore revision 1' })).toBeVisible()
  await page.getByLabel('Source node').selectOption({ label: source })
  await page.getByLabel('Destination IP').fill(destinationIP)
  await request('POST', network + '/policy-preview', () => page.getByRole('button', { name: 'Evaluate policy' }).click())
  await expect(page.getByRole('heading', { name: 'Current policy' })).toBeVisible()
  await expect(page.getByText('Allow', { exact: true })).toBeVisible()
  console.log('policy preview: displayed real history and evaluated the seeded TCP rule')

  await Promise.all([
    request('GET', network + '/topology', () => visit('/networks?view=map')),
    request('GET', network + '/node-locations'),
  ])
  await page.getByRole('button', { name: new RegExp(destination) }).click()
  await page.getByLabel('Site name').fill('Fleet console lab')
  await page.getByLabel('Latitude').fill('43.65')
  await page.getByLabel('Longitude').fill('-79.38')
  await request('PUT', /\/v1\/admin\/nodes\/[a-f0-9]+\/location$/, () =>
    page.getByRole('button', { name: 'Save location' }).click())
  await expect(page.getByText('Fleet console lab · Manual', { exact: true })).toBeVisible()
  console.log('map: fetched live topology and saved a manual fixture location')

  expect(errors, 'unhandled browser errors').toEqual([])
} finally {
  await browser.close()
}
